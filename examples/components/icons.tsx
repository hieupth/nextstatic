import type { SVGProps } from "react";

/**
 * Shared inline SVG base — stroke follows currentColor, so every icon
 * adapts to light/dark themes for free. Keep the set tiny on purpose.
 */
function Icon({ children, ...props }: SVGProps<SVGSVGElement>) {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={2}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden
      {...props}
    >
      {children}
    </svg>
  );
}

